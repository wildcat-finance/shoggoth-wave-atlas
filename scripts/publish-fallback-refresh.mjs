import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import { inspectSnapshot } from "./snapshot-validation.mjs";

// Publish a refreshed fallback snapshot as one signed commit on one dedicated
// branch, behind one open pull request.
//
// Commits are made through GitHub's GraphQL `createCommitOnBranch` rather than
// `git push`. This repository requires verified signatures on every ref, and a
// commit created through that mutation is signed by GitHub. A workflow that
// pushed with a checkout credential would produce an unsigned commit and be
// refused by the ruleset, which is a slower way to learn the same thing. It
// also means no credential is ever written into a Git remote or config.

const REFRESH_BRANCH = process.env.REFRESH_BRANCH ?? "automation/fallback-refresh";
const BASE_BRANCH = process.env.BASE_BRANCH ?? "main";
const DATA_PATH = "app/waves-data.json";
const META_PATH = "app/waves-meta.json";

const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;
if (!token) {
  throw new Error("Set GITHUB_TOKEN to a token that may update the refresh branch.");
}
const repository = process.env.GITHUB_REPOSITORY;
if (!repository || !/^[^/]+\/[^/]+$/.test(repository)) {
  throw new Error("Set GITHUB_REPOSITORY to owner/repo.");
}
const [owner, repo] = repository.split("/");

// Every message this script prints is built here from statuses and paths. A
// response body is never echoed, so a credential cannot travel into the log
// through an error path.
async function rest(method, path, body) {
  const response = await fetch(`https://api.github.com/repos/${repository}${path}`, {
    method,
    headers: {
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
      "User-Agent": "shoggoth-wave-atlas-fallback-refresh",
      Authorization: `Bearer ${token}`,
      ...(body ? { "Content-Type": "application/json" } : {}),
    },
    ...(body ? { body: JSON.stringify(body) } : {}),
  });
  if (response.status === 404) return { status: 404, body: null };
  if (!response.ok) {
    throw new Error(`GitHub ${method} ${path} returned ${response.status}`);
  }
  return { status: response.status, body: await response.json() };
}

async function graphql(query, variables) {
  const response = await fetch("https://api.github.com/graphql", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "User-Agent": "shoggoth-wave-atlas-fallback-refresh",
      Authorization: `Bearer ${token}`,
    },
    body: JSON.stringify({ query, variables }),
  });
  if (!response.ok) {
    throw new Error(`GitHub GraphQL returned ${response.status}`);
  }
  const payload = await response.json();
  if (payload.errors?.length) {
    // GraphQL error messages describe the mutation, not the credential.
    throw new Error(`GitHub GraphQL refused the commit: ${payload.errors[0].message}`);
  }
  return payload.data;
}

const dataBytes = readFileSync(resolve(DATA_PATH));
const metaBytes = readFileSync(resolve(META_PATH));
const meta = JSON.parse(metaBytes.toString("utf8"));
const report = inspectSnapshot({ waves: JSON.parse(dataBytes.toString("utf8")), meta });
if (!report.ok) {
  // The workflow validates before calling this, so reaching here means the
  // files changed underneath the run. Publish nothing.
  console.error("Refusing to publish an invalid fallback snapshot:");
  for (const problem of report.problems) console.error(`  - ${problem}`);
  process.exit(1);
}

const base = await rest("GET", `/git/ref/heads/${BASE_BRANCH}`);
if (!base.body) throw new Error(`${BASE_BRANCH} has no ref`);
const baseOid = base.body.object.sha;

// Rebuild the refresh branch from the current base on every run. The branch
// carries one generated commit and nothing else, so a stale base would put an
// unrelated diff in front of a reviewer.
const existing = await rest("GET", `/git/ref/heads/${REFRESH_BRANCH}`);
if (!existing.body) {
  await rest("POST", "/git/refs", { ref: `refs/heads/${REFRESH_BRANCH}`, sha: baseOid });
} else if (existing.body.object.sha !== baseOid) {
  await rest("PATCH", `/git/refs/heads/${REFRESH_BRANCH}`, { sha: baseOid, force: true });
}

const headline = `chore: refresh the checked-in fallback snapshot`;
const body = [
  `Skills revision \`${meta.source_revision}\` observed at ${meta.generated_at}.`,
  `${report.waveCount} waves, ${report.memberCount} issues, ${report.droppedCount} open issue(s) without a milestone.`,
  "",
  "Generated by the scheduled fallback refresh. Recovery path: `node scripts/sync-waves.mjs`.",
].join("\n");

await graphql(
  `mutation ($input: CreateCommitOnBranchInput!) {
     createCommitOnBranch(input: $input) { commit { oid } }
   }`,
  {
    input: {
      branch: { repositoryNameWithOwner: repository, branchName: REFRESH_BRANCH },
      message: { headline, body },
      expectedHeadOid: baseOid,
      fileChanges: {
        additions: [
          { path: DATA_PATH, contents: dataBytes.toString("base64") },
          { path: META_PATH, contents: metaBytes.toString("base64") },
        ],
      },
    },
  },
);

const prBody = [
  "The checked-in fallback answers `/api/job` only when the live GitHub read fails.",
  "It ages on its own, so this pull request keeps the recovery floor current.",
  "",
  `- Generated at: ${meta.generated_at}`,
  `- Skills revision: \`${meta.source_revision}\``,
  `- Waves: ${report.waveCount}`,
  `- Issues across waves: ${report.memberCount}`,
  `- Open issues with no milestone (never offered): ${report.droppedCount}`,
  "",
  "Only `app/waves-data.json` and `app/waves-meta.json` change here. The",
  "runtime GitHub read and its 600-second cache remain the ordinary source;",
  "this pull request maintains the fallback and nothing else.",
  "",
  "The recorded Skills revision is provenance for separately paginated GitHub",
  "reads, not an atomic snapshot of the repository at that commit.",
  "",
  "---",
  "_Generated by [Claude Code](https://claude.ai/code)_",
].join("\n");

const open = await rest(
  "GET",
  `/pulls?state=open&base=${BASE_BRANCH}&head=${encodeURIComponent(`${owner}:${REFRESH_BRANCH}`)}`,
);
const openPulls = Array.isArray(open.body) ? open.body : [];

if (openPulls.length === 0) {
  const created = await rest("POST", "/pulls", {
    title: "chore: refresh the checked-in fallback snapshot",
    head: REFRESH_BRANCH,
    base: BASE_BRANCH,
    body: prBody,
  });
  console.log(`Opened ${repo} pull request #${created.body.number}.`);
} else {
  // One branch, one pull request. Overlapping runs are already serialised by
  // the workflow's concurrency group; this is the second belt.
  const [pull] = openPulls;
  await rest("PATCH", `/pulls/${pull.number}`, { body: prBody });
  console.log(`Updated ${repo} pull request #${pull.number}.`);
  for (const extra of openPulls.slice(1)) {
    console.log(`Warning: pull request #${extra.number} also targets ${REFRESH_BRANCH}.`);
  }
}
